/**
 * `npm run map:check` (contract part) — the geometry contract (SPEC/33 §3, gate D): every feature and spatial relation the
 * study's keys, items and texts depend on (`content/site/contract.json`), evaluated on the map built now.
 *
 *   checkContract(builtMap)   every relation measured on the built map; returns the violations (an empty list passes)
 *   contractCoverage()        every keyed item or text that names a feature or states a distance, matched to a contract entry
 *                             (`contract-coverage.ts`); returns the unmatched ones
 *
 * The contract is generated by `npm run map:contract:extract` (`contract-extract.ts`; its `features` and `relations`) and
 * hand-curated in its `curated` section, which the extractor keeps as it is. Every measure is in site metres (x east, y north of
 * IGN) and compass degrees.
 */

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  angleDiff, bearing, dist, geomDistance, inRings, lineCrossings, nearestPointOf, roadDistance, roadGraph, sectorOfBearing, type Geom, type P,
} from "./contract-geom.js";
import { SECTOR_WEDGES, type BuiltMap } from "./contract-map.js";
import { sortedEntries } from "../../../app/engine/deterministic-object.js";

export const CONTRACT_PATH = "content/site/contract.json";
const ROOT = fileURLToPath(new URL("../../../", import.meta.url));

export type RelationType = "distance" | "bearing" | "ahead_of_fire" | "on_road" | "crosses" | "within_sector" | "travel_time" | "adjacency" | "text_mention";

/**
 * How a relation's value is measured on the built map (`features` are contract feature ids):
 *   distance        shortest distance between features[0] and features[1] (m)
 *   bearing         bearing from features[0] to the point of features[1] nearest it (°)
 *   crossing_near   distance from features[2] to the nearest point where lines features[0] and features[1] cross (m; ∞ if none)
 *   crossing_count  how many times lines features[0] and features[1] cross
 *   bridge_near     distance from features[0] to the nearest bridge the build drew (m)
 *   sector          the sector (L1–L4 wedge from IGN) features[0] lies in
 *   sector_margin   degrees from features[0]'s bearing from IGN to the nearest sector boundary
 *   road_route      shortest drive from features[0] to features[1] on the roads of `params.classes`, avoiding `params.avoid` (m)
 *   fire_distance   shortest distance from the fire (`params.steps`, `params.layer` truth | reported) to features[0] (m; 0 if burned)
 *   fuel_distance   shortest distance from the fire (`params.steps`, `params.layer`) to a cell of the truth fuel grid of `params.fuels`
 *                   whose bearing from IGN lies in `params.wedge` [from, to] (m): the stand a text names
 *   inside          whether features[0] lies inside features[1]
 *   nearest_label   the label (of `params.styles`) nearest the middle of line features[0]: how crossings.ts names a road
 *   label_present   whether the map carries the label `params.text`, in Finnish and (as `params.en`) in English
 */
export type Measure = "distance" | "bearing" | "crossing_near" | "crossing_count" | "bridge_near" | "sector" | "sector_margin" | "road_route" | "fire_distance" | "fuel_distance" | "inside" | "nearest_label" | "label_present";

export type Tolerance =
  | { readonly kind: "relative"; readonly value: number }
  | { readonly kind: "absolute"; readonly value: number }
  | { readonly kind: "exact" }
  | { readonly kind: "range"; readonly min?: number; readonly max?: number };

export interface UsedBy {
  readonly file: string;
  /** An item, record or constant id (freeze.<view>.<slug>, a traffic id, a deployment anchor …). */
  readonly id?: string;
  /** A regular expression (source) that finds the dependent texts, for coverage. */
  readonly pattern?: string;
  readonly note?: string;
}

export interface Relation {
  readonly id: string;
  readonly type: RelationType;
  readonly measure: Measure;
  readonly features: readonly string[];
  readonly params?: Readonly<Record<string, unknown>>;
  readonly value: number | string | boolean;
  readonly unit?: string;
  readonly tolerance: Tolerance;
  readonly usedBy: readonly UsedBy[];
  readonly note?: string;
  /**
   * Curated only: the map the scenario was authored on already fails this relation, and why. Its violation is still reported, marked
   * known; it does not fail `map:check`. The rebuild should meet it (or the text be re-authored and the mark removed).
   */
  readonly knownViolation?: string;
}

export interface ContractFeature {
  readonly id: string;
  readonly kind: string;
  readonly names: { readonly fi: string; readonly en: string };
  readonly match?: string;
  readonly geometry: unknown;
  readonly sources: readonly string[];
}

/** A text rule (curated): distances in texts of this pattern are derived, not fixed by the map (see `category`). */
export interface TextRule { readonly id: string; readonly pattern: string; readonly category: string; readonly source: string; readonly note: string }

export interface Contract {
  readonly version: number;
  readonly features: readonly ContractFeature[];
  readonly relations: readonly Relation[];
  readonly curated: { readonly features: readonly ContractFeature[]; readonly relations: readonly Relation[]; readonly textRules: readonly TextRule[] };
}

export interface Violation {
  readonly relation: string; readonly type: RelationType; readonly expected: string; readonly actual: string; readonly message: string;
  /** The relation's `knownViolation`: the authored map already fails it (reported, not counted). */
  readonly known?: string;
}

/** The violations that fail the check: all but the curated known ones. */
export const newViolations = (vs: readonly Violation[]): Violation[] => vs.filter((v) => v.known === undefined);

export function readContract(): Contract {
  return JSON.parse(readFileSync(ROOT + CONTRACT_PATH, "utf8")) as Contract;
}

/** Generated and curated relations, in that order. */
export const allRelations = (c: Contract): readonly Relation[] => [...c.relations, ...c.curated.relations];
export const allFeatures = (c: Contract): readonly ContractFeature[] => [...c.features, ...c.curated.features];

const SECTORS = sortedEntries(SECTOR_WEDGES).map(([id, w]) => ({ id, fromDeg: w.fromDeg, toDeg: w.toDeg }));
const IGN: P = { x: 0, y: 0 };
const asPoint = (g: Geom): P => {
  if (g.kind === "point") return g.p;
  if (g.kind === "line") return g.pts[Math.floor(g.pts.length / 2)]!;
  if (g.kind === "polygon") { const r = g.rings[0]!; return { x: r.reduce((a, p) => a + p.x, 0) / r.length, y: r.reduce((a, p) => a + p.y, 0) / r.length }; }
  return IGN;
};
const asLine = (g: Geom): readonly P[] => (g.kind === "line" ? g.pts : g.kind === "polygon" ? [...g.rings[0]!, g.rings[0]![0]!] : [asPoint(g)]);

/** A point's distance to a polygon, or ∞ when the polygon's outer ring's bounding box is already `cap` or more away. */
function nearIfCloser(p: P, rings: readonly (readonly P[])[], cap: number): number {
  const r = rings[0]!;
  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  for (const q of r) { minX = Math.min(minX, q.x); maxX = Math.max(maxX, q.x); minY = Math.min(minY, q.y); maxY = Math.max(maxY, q.y); }
  if (Math.hypot(Math.max(minX - p.x, 0, p.x - maxX), Math.max(minY - p.y, 0, p.y - maxY)) >= cap) return Infinity;
  return geomDistance({ kind: "point", p }, { kind: "polygon", rings });
}

const graphCache = new WeakMap<BuiltMap, Map<string, ReturnType<typeof roadGraph>>>();
function graphFor(map: BuiltMap, classes: readonly string[], avoid: readonly P[]) {
  const key = `${classes.join(",")}|${avoid.map((p) => `${Math.round(p.x)},${Math.round(p.y)}`).join(";")}`;
  const cache = graphCache.get(map) ?? graphCache.set(map, new Map()).get(map)!;
  if (!cache.has(key)) cache.set(key, roadGraph(map.roads.filter((r) => classes.includes(r.cls)).map((r) => r.line), 20, 50, avoid, 40));
  return cache.get(key)!;
}

/** The relation's value on the built map; throws on a missing feature (reported as a violation). */
export function measure(rel: Relation, map: BuiltMap): number | string | boolean {
  const g = (i: number): Geom => {
    const id = rel.features[i];
    const geom = id === undefined ? undefined : map.features[id];
    if (!geom) throw new Error(`feature ${id ?? `#${i}`} is missing from the built map`);
    return geom;
  };
  const p = rel.params ?? {};
  switch (rel.measure) {
    case "distance": return geomDistance(g(0), g(1));
    case "bearing": { const a = asPoint(g(0)); return bearing(a, nearestPointOf(a, g(1))); }
    case "crossing_near": {
      const hits = lineCrossings(asLine(g(0)), asLine(g(1)));
      const near = asPoint(g(2));
      return hits.length === 0 ? Infinity : Math.min(...hits.map((h) => dist(h, near)));
    }
    case "crossing_count": return lineCrossings(asLine(g(0)), asLine(g(1))).length;
    case "bridge_near": { const a = asPoint(g(0)); return map.bridges.length === 0 ? Infinity : Math.min(...map.bridges.map((b) => dist(a, b))); }
    case "sector": { const s = sectorOfBearing(bearing(IGN, asPoint(g(0))), SECTORS); return s < 0 ? "none" : SECTORS[s]!.id; }
    case "sector_margin": {
      const b = bearing(IGN, asPoint(g(0)));
      return Math.min(...SECTORS.map((s) => Math.abs(angleDiff(b, s.fromDeg))));
    }
    case "road_route": {
      const classes = (p["classes"] as string[] | undefined) ?? ["main", "gravel", "forest"];
      const avoid = ((p["avoid"] as string[] | undefined) ?? []).map((id) => {
        const a = map.features[id];
        if (!a) throw new Error(`feature ${id} (avoided) is missing from the built map`);
        return asPoint(a);
      });
      return roadDistance(graphFor(map, classes, avoid), asPoint(g(0)), asPoint(g(1)));
    }
    case "fire_distance": {
      const steps = (p["steps"] as number[] | undefined) ?? [];
      const layer = (p["layer"] as "truth" | "reported" | undefined) ?? "truth";
      if (map.fire.size === 0) throw new Error("the built map was read without the fire");
      const target = g(0);
      const at = asPoint(target);
      let best = Infinity;
      for (const st of steps) {
        const fs = map.fire.get(st);
        if (!fs) throw new Error(`the fire has no step ${st}`);
        for (const poly of fs[layer]) {
          if (poly.length === 0) continue;
          if (target.kind === "point" && inRings(at, poly)) return 0;
          best = Math.min(best, geomDistance({ kind: "polygon", rings: poly }, target));
        }
      }
      return best;
    }
    case "fuel_distance": {
      const steps = (p["steps"] as number[] | undefined) ?? [];
      const layer = (p["layer"] as "truth" | "reported" | undefined) ?? "truth";
      const [from, to] = (p["wedge"] as [number, number] | undefined) ?? [0, 360];
      const cells = ((p["fuels"] as string[] | undefined) ?? []).flatMap((f) => map.fuelCells.get(f) ?? []).filter((c) => { const b = bearing(IGN, c); return b >= from && b <= to; });
      if (cells.length === 0) throw new Error(`no ${String(p["fuels"])} cells at bearing ${from}–${to}° on the built fuel grid`);
      if (map.fire.size === 0) throw new Error("the built map was read without the fire");
      let best = Infinity;
      for (const st of steps) {
        const fs = map.fire.get(st);
        if (!fs) throw new Error(`the fire has no step ${st}`);
        for (const poly of fs[layer]) if (poly.length > 0) for (const c of cells) best = Math.min(best, nearIfCloser(c, poly, best));
      }
      return best;
    }
    case "inside": { const a = asPoint(g(0)); const h = g(1); return h.kind === "polygon" ? inRings(a, h.rings) : geomDistance({ kind: "point", p: a }, h) === 0; }
    case "nearest_label": {
      const styles = p["styles"] as string[] | undefined;
      const line = asLine(g(0));
      const mid = line[Math.floor(line.length / 2)]!;
      const labels = map.labels.fi.filter((l) => !styles || styles.includes(l.style));
      return labels.reduce((a, l) => (dist(l.p, mid) < dist(a.p, mid) ? l : a)).text;
    }
    case "label_present": {
      const text = p["text"] as string;
      const en = p["en"] as string | undefined;
      return map.labels.fi.some((l) => l.text === text) && (en === undefined || map.labels.en.some((l) => l.text === en));
    }
  }
}

/** Whether `actual` meets the relation's value within its tolerance. */
export function withinTolerance(rel: Relation, actual: number | string | boolean): boolean {
  const t = rel.tolerance;
  // Unreachable or absent (∞): passes only an open-ended minimum ("at least … m", e.g. a detour that must leave the map).
  if (typeof actual === "number" && !Number.isFinite(actual)) return t.kind === "range" && t.max === undefined;
  if (t.kind === "range" && typeof actual === "number") return (t.min === undefined || actual >= t.min) && (t.max === undefined || actual <= t.max);
  if (typeof actual !== "number" || typeof rel.value !== "number") return actual === rel.value;
  const diff = rel.measure === "bearing" ? Math.abs(angleDiff(actual, rel.value)) : Math.abs(actual - rel.value);
  switch (t.kind) {
    case "relative": return diff <= Math.abs(rel.value) * t.value;
    case "absolute": return diff <= t.value;
    case "exact": return diff === 0;
    default: return false;
  }
}

const show = (v: number | string | boolean, unit?: string) => (typeof v === "number" ? `${Number.isFinite(v) ? Math.round(v * 10) / 10 : "∞"}${unit ? ` ${unit}` : ""}` : String(v));
const showTol = (r: Relation): string => {
  const t = r.tolerance;
  switch (t.kind) {
    case "relative": return `${show(r.value, r.unit)} ±${Math.round(t.value * 100)} %`;
    case "absolute": return `${show(r.value, r.unit)} ±${t.value}${r.unit ? ` ${r.unit}` : ""}`;
    case "exact": return `${show(r.value, r.unit)} exactly`;
    case "range": return `${t.min ?? "−∞"}…${t.max ?? "∞"}${r.unit ? ` ${r.unit}` : ""}`;
  }
};

/** Evaluates every relation of the contract on the built map. An empty list: the map meets the contract. */
export function checkContract(builtMap: BuiltMap, contract: Contract = readContract()): Violation[] {
  const out: Violation[] = [];
  for (const rel of allRelations(contract)) {
    const known = rel.knownViolation !== undefined ? { known: rel.knownViolation } : {};
    let actual: number | string | boolean;
    try {
      actual = measure(rel, builtMap);
    } catch (e) {
      out.push({ relation: rel.id, type: rel.type, expected: showTol(rel), actual: "—", message: `${rel.id}: ${(e as Error).message}`, ...known });
      continue;
    }
    if (!withinTolerance(rel, actual)) {
      out.push({ relation: rel.id, type: rel.type, expected: showTol(rel), actual: show(actual, rel.unit), message: `${rel.id} (${rel.type}): ${show(actual, rel.unit)}, contract ${showTol(rel)}; used by ${rel.usedBy.map((u) => u.id ?? u.file).join(", ")}`, ...known });
    }
  }
  return out;
}

/** Ids that occur twice, and features a relation names that the contract does not define. */
export function contractIntegrity(c: Contract): string[] {
  const problems: string[] = [];
  const featureIds = new Set<string>();
  for (const f of allFeatures(c)) { if (featureIds.has(f.id)) problems.push(`feature ${f.id} defined twice`); featureIds.add(f.id); }
  const relIds = new Set<string>();
  for (const r of allRelations(c)) {
    if (relIds.has(r.id)) problems.push(`relation ${r.id} defined twice`);
    relIds.add(r.id);
    for (const f of r.features) if (!featureIds.has(f)) problems.push(`relation ${r.id} names undefined feature ${f}`);
    if (r.usedBy.length === 0) problems.push(`relation ${r.id} has no usedBy`);
  }
  return problems;
}

export async function main(): Promise<void> {
  const { loadBuiltMap } = await import("./contract-map.js");
  const { contractCoverage } = await import("./contract-coverage.js");
  const contract = readContract();
  const integrity = contractIntegrity(contract);
  const map = loadBuiltMap();
  const violations = checkContract(map, contract);
  const rels = allRelations(contract);
  console.log(`map:check — geometry contract (${CONTRACT_PATH}): ${allFeatures(contract).length} features, ${rels.length} relations`);
  for (const p of integrity) console.log(`  CONTRACT ${p}`);
  for (const v of violations) console.log(`  ${v.known === undefined ? "VIOLATION" : "KNOWN (authored map)"} ${v.message}${v.known === undefined ? "" : ` — ${v.known}`}`);
  const failing = newViolations(violations);
  console.log(`  ${failing.length} violation(s)${violations.length > failing.length ? `, ${violations.length - failing.length} known on the authored map` : ""}`);
  const cov = await contractCoverage(contract);
  console.log(`  coverage: ${cov.texts} texts read, ${cov.mentions} name or distance mentions, ${cov.unmatched.length} unmatched`);
  console.log(`  distances covered by: ${sortedEntries(cov.byRule).map(([k, n]) => `${k} ${n}`).join(", ")}`);
  for (const u of cov.unmatched.slice(0, process.argv.includes("--all") ? undefined : 40)) console.log(`  UNMATCHED ${u.source} ${u.id}: ${u.what} — "${u.excerpt}"`);
  if (!process.argv.includes("--all") && cov.unmatched.length > 40) console.log(`  … ${cov.unmatched.length - 40} more (--all lists them)`);
  const strict = process.argv.includes("--strict-coverage");
  if (integrity.length > 0 || failing.length > 0 || (strict && cov.unmatched.length > 0)) process.exitCode = 1;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) void main();
